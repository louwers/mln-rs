/// What a built-in program reads.
#[derive(Debug)]
pub struct ProgramInfo {
    /// The name its shader group is registered under.
    pub name: &'static str,
    pub program: BuiltIn,
    /// Each per-vertex attribute's id and format.
    pub attributes: &'static [(usize, AttributeDataType)],
    /// Each per-instance attribute's id and format.
    pub instance_attributes: &'static [(usize, AttributeDataType)],
    pub textures: &'static [usize],
}

