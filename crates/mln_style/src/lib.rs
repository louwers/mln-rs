//! The map style: [`Style`], the style JSON parser, layers and sources, the
//! property system and the typed converters (`conversion`). It also holds
//! the parts of the renderer and the map that the property system needs
//! (`renderer`, `map`), so that crates don't depend on each other in a
//! cycle.
//!
//! A style parses against a [`StyleRegistry`]: the expression functions and
//! layer types its JSON, property values and filters may name.
//!
//! Versions:
//! - A [`Style`] is a value: a version of a map's style. Its parts sit
//!   behind `Arc`s, so versions share what they don't change, and a part
//!   whose `Arc` is the same pointer in two versions is the same part.
//! - [`Style::apply`] makes an [`Edit`], the only way to change a style; the
//!   JSON entry points (`add_layer_json`, `set_layer_property_json`, ...)
//!   parse and then apply one.
//! - [`Style::is_same_version`] says in O(1) whether two versions are the
//!   same, and [`diff::StyleDiff::between`] what a renderer has to redo for
//!   each layer, source and image to go from one version to another.
//! - Loading isn't here: the map's loader fetches documents, sprites and
//!   source descriptions, and [`Style::from_json`] parses a document. A
//!   style holds its sources as values ([`SourceList`]), and what their
//!   loads find arrives as edits.
//!
//! Layers:
//! - `layer::Layer` is a layer of any type. Its style data is an
//!   `Arc<dyn layer_type::ErasedLayerStyle>`, a `layer_type::LayerStyle<T>`
//!   of its type `T`; `layer_type::LayerBase` holds the members every layer
//!   type has.
//! - Each layer type is a marker type that implements
//!   `layer_type::StyleLayerType`, such as `layers::Background`, with
//!   property sets such as
//!   `layers::BackgroundPaintProperties::{Transitionable, Unevaluated, PossiblyEvaluated, Evaluated}`.
//! - Each layer type, the light and the sky have a property table, which
//!   `property_table` reads to get, set and serialize properties by name.
//!   `layers/<type>_layer_properties.rs`, `light_properties.rs` and
//!   `sky_properties.rs` are generated by //tools/style-codegen from the style
//!   spec.

