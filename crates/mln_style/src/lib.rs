//! The map style: `Style` and its `style::Impl`, the style JSON parser,
//! layers and sources, the property system and the typed converters
//! (`conversion`). It also holds the parts of the renderer and the map that
//! the property system needs (`renderer`, `map`) and the style half of the
//! layer manager (`layermanager`), so that crates don't depend on each other
//! in a cycle.
//!
//! Layers:
//! - `layer::Layer` is the layer trait. A layer's data is an
//!   `Arc<dyn layer::Impl>`; `layer::ImplBase` holds the members every layer
//!   type has.
//! - Each layer type has a module such as
//!   `layers::background_layer::{BackgroundLayer, Impl}`, and property sets
//!   such as
//!   `layers::BackgroundPaintProperties::{Transitionable, Unevaluated, PossiblyEvaluated, Evaluated}`.
//!   `layers/<type>_layer.rs`, `layers/<type>_layer_properties.rs`,
//!   `light.rs` and `sky.rs` are generated by //tools/style-codegen from the
//!   style spec.

