#!/usr/bin/env python3
"""Writes the tables that mln_text's Arabic shaping reads
(src/arabic_tables.rs) from the Unicode Character Database: joining types
from ArabicShaping.txt, and presentation forms from the <isolated>, <final>,
<initial> and <medial> decompositions in UnicodeData.txt.

Usage: gen_arabic_shaping.py ArabicShaping.txt UnicodeData.txt

The UCD version is the one of unicode-bidi's own tables, as for the BiDi
mirroring table. `mise run generate:arabic-shaping` downloads both files and
writes the tables.
"""

import re
import sys

LAM = 0x0644
TATWEEL = 0x0640
SPACE = 0x0020
FORM_TAGS = ["<isolated>", "<final>", "<initial>", "<medial>"]


def read_joining_types(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    version = re.search(r"^# ArabicShaping-([\d.]+)\.txt", text, re.M)
    if not version:
        raise SystemExit("not an ArabicShaping.txt")
    types = {}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [field.strip() for field in line.split(";")]
        types[int(fields[0], 16)] = fields[2]
    return version.group(1), types


def read_unicode_data(path):
    """Each character's general category, and its decompositions as
    (character, tag, components)."""
    categories = {}
    decompositions = []
    with open(path, encoding="utf-8") as f:
        rows = [line.rstrip("\n").split(";") for line in f if line.strip()]
    i = 0
    while i < len(rows):
        fields = rows[i]
        code = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            last = int(rows[i + 1][0], 16)
            for c in range(code, last + 1):
                categories[c] = fields[2]
            i += 2
            continue
        categories[code] = fields[2]
        if fields[5].startswith("<"):
            tag, *components = fields[5].split()
            decompositions.append((code, tag, tuple(int(c, 16) for c in components)))
        i += 1
    return categories, decompositions


def joining_type(c, explicit, categories):
    # ArabicShaping.txt: characters it doesn't list are Transparent if their
    # general category is Mn, Me or Cf, and Non_Joining otherwise.
    if c in explicit:
        return explicit[c]
    return "T" if categories.get(c) in ("Mn", "Me", "Cf") else "U"


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    version, explicit = read_joining_types(sys.argv[1])
    categories, decompositions = read_unicode_data(sys.argv[2])

    def jt(c):
        return joining_type(c, explicit, categories)

    # Ranges of BMP characters by joining type, Non_Joining left out.
    ranges = []
    for c in range(0x10000):
        t = jt(c)
        if t == "U":
            continue
        if ranges and ranges[-1][2] == t and ranges[-1][1] == c - 1:
            ranges[-1][1] = c
        else:
            ranges.append([c, c, t])

    letters = {}
    lam_alef = {}
    marks = {}
    for code, tag, components in decompositions:
        if tag not in FORM_TAGS:
            continue
        form = FORM_TAGS.index(tag)
        if code > 0xFFFF:
            raise SystemExit(f"presentation form U+{code:04X} is outside the BMP")
        if len(components) == 1:
            entry = letters.setdefault(components[0], [0, 0, 0, 0])
            if entry[form]:
                raise SystemExit(f"two {tag} forms of U+{components[0]:04X}")
            entry[form] = code
        elif len(components) == 2 and components[0] == LAM and jt(components[1]) == "R":
            # Lam with a right-joining letter, which ends the join: the
            # lam-alef ligatures, isolated or final.
            entry = lam_alef.setdefault(components[1], [0, 0])
            entry[form] = code
        elif len(components) == 2 and jt(components[1]) == "T" and (form, components[0]) in (
            (0, SPACE),
            (3, TATWEEL),
        ):
            # A mark on its own (on a space) or on a tatweel.
            entry = marks.setdefault(components[1], [0, 0])
            entry[0 if form == 0 else 1] = code

    for letter, forms in letters.items():
        t = jt(letter)
        expected = {"D": [1, 1, 1, 1], "R": [1, 1, 0, 0], "U": [1, 0, 0, 0]}.get(t)
        if letter > 0xFFFF or expected is None:
            raise SystemExit(f"U+{letter:04X} has forms but joining type {t}")
        # A letter has the forms of its joining type, at most.
        if any(f and not e for f, e in zip(forms, expected)):
            raise SystemExit(f"U+{letter:04X} ({t}) has forms {forms}")
    if any(not all(forms) for forms in lam_alef.values()) or not lam_alef:
        raise SystemExit(f"lam-alef ligatures without both forms: {lam_alef}")
    if any(not forms[0] for forms in marks.values()) or not marks:
        raise SystemExit(f"marks without an isolated form: {marks}")

    def hexes(values):
        return ", ".join(f"0x{v:04x}" for v in values)

    print("// Generated by crates/mln_text/tools/gen_arabic_shaping.py from the Unicode")
    print(f"// Character Database's ArabicShaping-{version}.txt and UnicodeData.txt. Do not edit.")
    print()
    print("use crate::arabic::JoiningType::{self, Dual as D, JoinCausing as C, Left as L, Right as R, Transparent as T};")
    print()
    print("/// Ranges of BMP characters, first and last, with the joining type of each")
    print("/// character in the range, sorted. Characters in none are non-joining.")
    print(f"pub(crate) static JOINING_TYPES: [(u16, u16, JoiningType); {len(ranges)}] = [")
    per_line = 5
    for i in range(0, len(ranges), per_line):
        row = ", ".join(f"(0x{a:04x}, 0x{b:04x}, {t})" for a, b, t in ranges[i : i + per_line])
        print(f"    {row},")
    print("];")
    print()
    print("/// Each letter with presentation forms, and its isolated, final, initial and")
    print("/// medial forms (0 where it has none), sorted by letter.")
    print(f"pub(crate) static LETTER_FORMS: [(u16, [u16; 4]); {len(letters)}] = [")
    for letter in sorted(letters):
        print(f"    (0x{letter:04x}, [{hexes(letters[letter])}]),")
    print("];")
    print()
    print("/// Each letter that a lam before it ligates with, and the ligature's isolated")
    print("/// and final forms, sorted by letter.")
    print(f"pub(crate) static LAM_ALEF_FORMS: [(u16, [u16; 2]); {len(lam_alef)}] = [")
    for alef in sorted(lam_alef):
        print(f"    (0x{alef:04x}, [{hexes(lam_alef[alef])}]),")
    print("];")
    print()
    print("/// Each mark with presentation forms, and its forms on its own and on a")
    print("/// tatweel (0 where it has none), sorted by mark.")
    print(f"pub(crate) static MARK_FORMS: [(u16, [u16; 2]); {len(marks)}] = [")
    for mark in sorted(marks):
        print(f"    (0x{mark:04x}, [{hexes(marks[mark])}]),")
    print("];")


if __name__ == "__main__":
    main()
