#!/usr/bin/env python3
"""Writes the Bidi_Mirroring_Glyph table that mln_text's BiDi reads
(src/bidi_mirroring.rs) from the Unicode Character Database's
BidiMirroring.txt, read from stdin.

The UCD version is the one of unicode-bidi's own tables, so that the
characters it resolves as right to left and the ones mirrored come from the
same Unicode version. `mise run generate:bidi-mirroring` downloads it and
writes the table.
"""

import re
import sys


def main():
    text = sys.stdin.read()
    version = re.search(r"^# BidiMirroring-([\d.]+)\.txt", text, re.M)
    if not version:
        raise SystemExit("not a BidiMirroring.txt")
    pairs = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        source, mirror = (int(field, 16) for field in line.split(";"))
        # The table stores UTF-16 code units: every mirrored character is in
        # the BMP.
        if source > 0xFFFF or mirror > 0xFFFF:
            raise SystemExit(f"U+{source:04X} or its mirror is outside the BMP")
        pairs.append((source, mirror))
    pairs.sort()
    if not pairs or len({s for s, _ in pairs}) != len(pairs):
        raise SystemExit("no mappings, or a character mapped twice")

    print("// Generated by crates/mln_text/tools/gen_bidi_mirroring.py from the")
    print(f"// Unicode Character Database's BidiMirroring-{version.group(1)}.txt. Do not edit.")
    print()
    print("/// Each character with a `Bidi_Mirroring_Glyph`, and that glyph, sorted by")
    print("/// character.")
    print(f"pub(crate) static BIDI_MIRRORING_GLYPH: [(u16, u16); {len(pairs)}] = [")
    per_line = 6
    for i in range(0, len(pairs), per_line):
        row = ", ".join(f"(0x{s:04x}, 0x{m:04x})" for s, m in pairs[i : i + per_line])
        print(f"    {row},")
    print("];")


if __name__ == "__main__":
    main()
