#!/usr/bin/env python3
"""Generates crates/mln_text/src/hb_ucd_table.rs from the C++ core's vendored
HarfBuzz (vendor/harfbuzz/src/hb-ucd-table.hh, hb-common.h).

The C++ core builds HarfBuzz with HB_TINY, which defines HB_OPTIMIZE_SIZE and
HB_NO_UCD_UNASSIGNED, so hb-ucd-table.hh compiles its third variant (the
`#else` branch). This script ports exactly that variant's general category
(`_hb_ucd_gc`) and script (`_hb_ucd_sc`) lookups and `_hb_ucd_sc_map`.

`just generate-hb-ucd-tables` writes both tables below.

Usage: gen_hb_ucd.py <path to ../maplibre-native> > src/hb_ucd_table.rs

With `--full-gc` it emits instead the general category of the first variant
(the full table, where unassigned codepoints are Cn), for
//difftest/text/hb_ucd15_full_gc.rs (finding codepoints unassigned in
Unicode 15.0, whose HB_TINY properties are arbitrary):
  gen_hb_ucd.py <path to ../maplibre-native> --full-gc > ../../difftest/text/hb_ucd15_full_gc.rs
"""

import re
import sys


def main():
    cpp = sys.argv[1]
    full_gc = "--full-gc" in sys.argv[2:]
    with open(f"{cpp}/vendor/harfbuzz/src/hb-ucd-table.hh") as f:
        table = f.read()
    with open(f"{cpp}/vendor/harfbuzz/src/hb-common.h") as f:
        common = f.read()

    # Script names -> tags.
    tags = {}
    for m in re.finditer(
        r"(HB_SCRIPT_\w+)\s*=\s*HB_TAG\s*\('(.)','(.)','(.)','(.)'\)", common
    ):
        tags[m.group(1)] = "".join(m.group(i) for i in range(2, 6))

    # _hb_ucd_sc_map (shared by all variants).
    m = re.search(r"_hb_ucd_sc_map\[(\d+)\]\s*=\s*\{(.*?)\};", table, re.S)
    sc_count = int(m.group(1))
    sc_names = re.findall(r"HB_SCRIPT_\w+", m.group(2))
    assert len(sc_names) == sc_count, (len(sc_names), sc_count)

    lines = table.split("\n")
    if full_gc:
        # The first variant: `#ifndef HB_OPTIMIZE_SIZE` .. `#elif`.
        start = next(i for i, l in enumerate(lines) if l.strip() == "#ifndef HB_OPTIMIZE_SIZE")
        end = next(i for i, l in enumerate(lines) if i > start and l.strip().startswith("#elif"))
        variant = "\n".join(lines[start:end])
    else:
        # The third variant: after the last `#else` of the file.
        variant_start = max(i for i, l in enumerate(lines) if l.strip() == "#else")
        variant = "\n".join(lines[variant_start:])

    arrays = {}
    for m in re.finditer(
        r"static const (uint8_t|uint16_t|int16_t)\s*\n(_hb_ucd_\w+)\[(\d+)\]\s*=\s*\{(.*?)\};",
        variant,
        re.S,
    ):
        ctype, name, count, body = m.groups()
        values = [int(v) for v in re.findall(r"-?\d+", body)]
        assert len(values) == int(count), (name, len(values), count)
        arrays[name] = (ctype, values)

    funcs = {}
    for m in re.finditer(
        r"static inline \w+\s*\n(_hb_ucd_\w+) \(unsigned u\)\s*\n\{\s*\n\s*return (.*?);\s*\n\}",
        variant,
    ):
        funcs[m.group(1)] = m.group(2)

    out = []
    if full_gc:
        out.append("// Generated by crates/mln_text/tools/gen_hb_ucd.py --full-gc from")
        out.append("// ../maplibre-native/vendor/harfbuzz/src/hb-ucd-table.hh: the general category")
        out.append("// of the full (first) variant, Unicode 15.0.0, where unassigned codepoints are Cn.")
        out.append("// Do not edit.")
        out.append("")
        emit_funcs(out, arrays, funcs, (("_hb_ucd_gc", "full_gc"),))
        sys.stdout.write("\n".join(out))
        return
    out.append("// Generated by crates/mln_text/tools/gen_hb_ucd.py from")
    out.append("// ../maplibre-native/vendor/harfbuzz/src/hb-ucd-table.hh (Unicode 15.0.0,")
    out.append("// the HB_OPTIMIZE_SIZE + HB_NO_UCD_UNASSIGNED variant that HB_TINY selects).")
    out.append("// Do not edit.")
    out.append("")
    out.append("#![allow(clippy::all)]")
    out.append("")
    out.append(f"/// `_hb_ucd_sc_map`: script tags (ISO 15924) by `_hb_ucd_sc` index.")
    out.append(f"pub static SC_MAP: [[u8; 4]; {sc_count}] = [")
    for name in sc_names:
        out.append(f"    *b\"{tags[name]}\", // {name}")
    out.append("];")
    out.append("")

    emit_funcs(out, arrays, funcs, (("_hb_ucd_gc", "gc"), ("_hb_ucd_sc", "sc")))

    sys.stdout.write("\n".join(out))


def emit_funcs(out, arrays, funcs, names):
    """The arrays the named lookups use and the lookups, as Rust."""
    rust_types = {"uint8_t": "u8", "uint16_t": "u16", "int16_t": "i16"}
    used = set()
    for fname, _ in names:
        used.update(re.findall(r"_hb_ucd_(u8|u16|i16)\[", funcs[fname]))
        assert "_hb_ucd_b4" not in funcs[fname], fname
    for short in sorted(used):
        name = f"_hb_ucd_{short}"
        ctype, values = arrays[name]
        rt = rust_types[ctype]
        out.append(f"static {short.upper()}: [{rt}; {len(values)}] = [")
        for i in range(0, len(values), 16):
            out.append("    " + ", ".join(str(v) for v in values[i : i + 16]) + ",")
        out.append("];")
        out.append("")
        out.append("#[inline]")
        out.append(f"fn {short}_at(i: usize) -> usize {{")
        out.append(f"    {short.upper()}[i] as usize")
        out.append("}")
        out.append("")

    for fname, rname in names:
        expr = funcs[fname]
        m = re.fullmatch(r"u<(\d+)u\?(.*):(\d+)", expr)
        assert m, expr
        limit, body, default = m.groups()
        body = re.sub(r"(\d+)u\b", r"\1", body)
        body = re.sub(r"_hb_ucd_(u8|u16|i16)\[", r"\1_at(", body)
        body = body.replace("[", "(").replace("]", ")")
        out.append(f"/// `{fname}`.")
        out.append("#[inline]")
        out.append(f"pub fn {rname}(u: u32) -> u8 {{")
        out.append("    let u = u as usize;")
        out.append(f"    if u < {int(limit):_} {{")
        out.append(f"        ({body}) as u8")
        out.append("    } else {")
        out.append(f"        {default}")
        out.append("    }")
        out.append("}")
        out.append("")


if __name__ == "__main__":
    main()
