#!/usr/bin/env python3
"""Generates the ICU property table that the BiDi port reads, from ICU
78.3's compiled-in property data: the version the Linux C++ build links
(the #linux dev shell's icu4c 78.3, `-licuuc`; platform/default/BUILD.bazel).

`ubidi_props_data.h` (Bidi_Class, mirroring, paired brackets) is UTrie2 data
that ICU compiles into libicuuc, so the table is the data the C++ oracle
uses, not a re-derivation from the UCD.

`mise run generate:icu-tables <dir>/icu/source/common` writes the table.

Usage, from crates/mln_text:
  nix-store --realise /nix/store/...-icu4c-78.3-sources.tgz.drv   # or any ICU 78.3 source tree
  tar xzf <icu4c-78.3-sources.tgz> icu/source/common/ubidi_props_data.h
  gen_icu_tables.py <dir>/icu/source/common > src/icu/ubidi_props_data.rs
"""

import re
import sys


def c_array(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\[(\w+)\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit(f"array {name} not found")
    values = [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", m.group(2))]
    if m.group(1).isdigit():
        assert len(values) == int(m.group(1)), name
    return values


def trie_params(text, struct_name, index_name):
    """The UTrie2 initializer: index, data16, data32, indexLength,
    dataLength, index2NullOffset, dataNullOffset, initialValue, errorValue,
    highStart, highValueIndex."""
    m = re.search(re.escape(struct_name) + r"\s*=\s*\{(.*?)\};", text, re.S)
    body = m.group(1)
    if "{" in body:  # nested in UBiDiProps
        body = body[body.index("{") + 1 :]
    fields = [f.strip() for f in body.split(",")]
    assert fields[0] == index_name, fields[0]
    return {
        "indexLength": int(fields[3], 0),
        "dataLength": int(fields[4], 0),
        "highStart": int(fields[9], 0),
        "highValueIndex": int(fields[10], 0),
    }


def rust_array(name, ty, values, per_line=16):
    out = [f"pub(crate) static {name}: [{ty}; {len(values)}] = ["]
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(f"0x{v:x}" for v in values[i : i + per_line]) + ",")
    out.append("];")
    return "\n".join(out)


def bidi(common):
    with open(f"{common}/ubidi_props_data.h") as f:
        text = f.read()
    version = re.search(r"ubidi_props_dataVersion=\{([^}]*)\}", text).group(1)
    indexes = c_array(text, "ubidi_props_indexes")
    trie_index = c_array(text, "ubidi_props_trieIndex")
    mirrors = c_array(text, "ubidi_props_mirrors")
    params = trie_params(text, "ubidi_props_singleton", "ubidi_props_trieIndex")
    print("// Generated by crates/mln_text/tools/gen_icu_tables.py from ICU 78.3's")
    print("// icu4c/source/common/ubidi_props_data.h (machine-generated by ICU's")
    print(f"// genprops/bidipropsbuilder.cpp; data version {{{version}}}). Do not edit.")
    print()
    print('#![expect(clippy::unreadable_literal, reason = "the tables are ICU\'s, in its hexadecimal")]')
    print()
    print(rust_array("UBIDI_PROPS_INDEXES", "i32", indexes))
    print()
    print(rust_array("UBIDI_PROPS_TRIE_INDEX", "u16", trie_index))
    print()
    print(rust_array("UBIDI_PROPS_MIRRORS", "u32", mirrors, 8))
    print()
    print("/// The `UTrie2` fields of `ubidi_props_singleton.trie`.")
    print(f"pub(crate) const TRIE_INDEX_LENGTH: usize = {params['indexLength']};")
    print(f"pub(crate) const TRIE_DATA_LENGTH: usize = {params['dataLength']};")
    print(f"pub(crate) const TRIE_HIGH_START: u32 = 0x{params['highStart']:x};")
    print(f"pub(crate) const TRIE_HIGH_VALUE_INDEX: usize = 0x{params['highValueIndex']:x};")


def main():
    bidi(sys.argv[1])


if __name__ == "__main__":
    main()
