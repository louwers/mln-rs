use crate::emit_table::{Entry, Visit};
use crate::spec::Property;
use crate::types::snake;
use crate::writer::Writer;

/// The field of a root property: the object name plus the property's name,
/// without the object name for sky properties whose name already starts with
/// it.
fn field(object_name: &str, p: &Property) -> String {
    if p.name.starts_with(&format!("{object_name}-")) {
        format!("properties.{}", snake(&p.name))
    } else {
        format!("properties.{object_name}_{}", snake(&p.name))
    }
}

/// Emits the property table of a root object (`light` or `sky`), whose
/// type is `crate::{object_name}::{Object}`.
#[must_use]
pub(crate) fn emit(object_name: &str, properties: &[Property]) -> String {
    let mut w = Writer::new();
    w.line("// This file is generated by //tools/style-codegen from the style spec");
    w.line("// (tools/style-codegen/v8.json). Do not edit.");
    w.blank();

    let owner = crate::types::camelize(object_name);
    let mut imports = crate::emit_table::imports(&Visit::Impl);
    imports.push(format!("crate::{object_name}::{owner}"));
    w.imports(imports);
    w.blank();

    let entries: Vec<Entry<'_>> = properties
        .iter()
        .map(|property| Entry { property, paint: true, field: field(object_name, property) })
        .collect();
    crate::emit_table::emit(&mut w, &owner, &entries, &Visit::Impl);
    w.finish()
}
