use crate::emit_layer::{conversion_groups, let_else};
use crate::spec::Property;
use crate::types::{camelize, property_value_type, snake};
use crate::writer::{MAX_WIDTH, Writer, if_condition, imports_for};

/// The property's tag: the class name plus the camelized property name, without
/// the class name for sky properties whose name already starts with it.
fn type_name(class_name: &str, p: &Property) -> String {
    if class_name == "Sky" && p.name.starts_with("sky-") {
        camelize(&p.name)
    } else {
        format!("{class_name}{}", camelize(&p.name))
    }
}

/// Emits the root properties class `class_name` (`Light` from the spec's
/// `light`, `Sky` from its `sky`).
#[must_use]
pub(crate) fn emit(class_name: &str, object_name: &str, properties: &[Property]) -> String {
    let mut w = Writer::new();
    w.line("// This file is generated by //tools/style-codegen from the style spec");
    w.line("// (tools/style-codegen/v8.json). Do not edit.");
    w.blank();

    let mut imports = imports_for(properties.iter(), true);
    imports.push("crate::conversion::{Converter, convert_property_value}".into());
    imports.push("crate::conversion_impl::{make_style_property, make_transition_style_property}".into());
    imports.push("crate::property_value::PropertyValue".into());
    imports.push("crate::style_property::StyleProperty".into());
    imports.push("crate::transition_options::TransitionOptions".into());
    imports.push("mln_conversion::{Convertible, Error}".into());
    imports.push("std::sync::Arc".into());
    w.imports(imports);
    w.blank();

    let mut tags: Vec<String> = properties.iter().map(|p| type_name(class_name, p)).collect();
    tags.insert(0, "Impl".into());
    tags.push(format!("{class_name}Properties"));
    tags.sort_by(|a, b| {
        let key = |s: &str| (s != "Impl", s.to_owned());
        key(a).cmp(&key(b))
    });
    w.use_items("pub use", &format!("crate::{object_name}_impl"), &tags);
    w.blank();

    w.line("#[derive(Clone, Debug)]");
    w.line(&format!("pub struct {class_name} {{"));
    w.line("    pub impl_: Arc<Impl>,");
    w.line("}");
    w.blank();
    w.line(&format!("impl Default for {class_name} {{"));
    w.line("    fn default() -> Self {");
    w.line(&format!("        {class_name}::new()"));
    w.line("    }");
    w.line("}");
    w.blank();

    w.line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    w.line("#[repr(u8)]");
    w.line("enum Property {");
    for p in properties {
        w.line(&format!("    {},", camelize(&p.name)));
    }
    for p in properties {
        w.line(&format!("    {}Transition,", camelize(&p.name)));
    }
    w.line("}");
    w.blank();
    w.line("/// The style-spec name of each property.");
    w.line("const PROPERTIES: &[(&str, Property)] = &[");
    for p in properties {
        w.line(&format!("    (\"{}\", Property::{}),", p.name, camelize(&p.name)));
    }
    for p in properties {
        w.line(&format!("    (\"{}-transition\", Property::{}Transition),", p.name, camelize(&p.name)));
    }
    w.line("];");
    w.blank();
    w.line("fn find_property(name: &str) -> Option<Property> {");
    w.line("    PROPERTIES.iter().find(|(n, _)| *n == name).map(|(_, p)| *p)");
    w.line("}");
    w.blank();

    w.line(&format!("impl {class_name} {{"));
    w.line("    #[must_use]");
    w.line("    pub fn new() -> Self {");
    w.line(&format!("        {class_name}::from_impl(Arc::new(Impl::default()))"));
    w.line("    }");
    w.blank();
    w.line("    #[must_use]");
    w.line("    pub fn from_impl(impl_: Arc<Impl>) -> Self {");
    w.line(&format!("        {class_name} {{ impl_ }}"));
    w.line("    }");
    w.blank();
    w.line("    /// A copy of the impl, to change and store back.");
    w.line("    #[must_use]");
    w.line("    pub fn mutable_impl(&self) -> Impl {");
    w.line("        (*self.impl_).clone()");
    w.line("    }");
    w.blank();
    w.line("    // Dynamic properties");
    w.line("    pub fn set_property(&mut self, name: &str, value: &Convertible<'_>) -> Option<Error> {");
    w.line("        let Some(property) = find_property(name) else {");
    w.line(&format!("            return Some(Error::new(\"{object_name} doesn't support this property\"));"));
    w.line("        };");
    w.blank();
    for (key, members) in conversion_groups(properties.iter()) {
        let terms: Vec<String> =
            members.iter().map(|p| format!("property == Property::{}", camelize(&p.name))).collect();
        for line in if_condition("        ", &terms) {
            w.line(&line);
        }
        w.line("            let mut error = Error::default();");
        let_else(&mut w, "            ", &key);
        w.blank();
        if members.len() == 1 {
            w.line(&format!("            self.set_{}(typed_value);", snake(&members[0].name)));
            w.line("            return None;");
        } else {
            for (i, p) in members.iter().enumerate() {
                if i > 0 {
                    w.blank();
                }
                w.line(&format!("            if property == Property::{} {{", camelize(&p.name)));
                w.line(&format!("                self.set_{}(typed_value);", snake(&p.name)));
                w.line("                return None;");
                w.line("            }");
            }
        }
        w.line("        }");
        w.blank();
    }
    w.line("        let mut error = Error::default();");
    w.line("        let Some(transition) = <TransitionOptions as Converter>::convert(value, &mut error) else {");
    w.line("            return Some(error);");
    w.line("        };");
    w.blank();
    for p in properties {
        w.line(&format!("        if property == Property::{}Transition {{", camelize(&p.name)));
        w.line(&format!("            self.set_{}_transition(&transition);", snake(&p.name)));
        w.line("            return None;");
        w.line("        }");
        w.blank();
    }
    w.line(&format!("        Some(Error::new(\"{object_name} doesn't support this property\"))"));
    w.line("    }");
    w.blank();
    w.line("    #[must_use]");
    w.line("    pub fn get_property(&self, name: &str) -> StyleProperty {");
    w.line("        let Some(property) = find_property(name) else {");
    w.line("            return StyleProperty::default();");
    w.line("        };");
    w.blank();
    w.line("        match property {");
    for p in properties {
        w.line(&format!(
            "            Property::{} => make_style_property(&self.get_{}()),",
            camelize(&p.name),
            snake(&p.name)
        ));
    }
    for p in properties {
        let arm = format!(
            "            Property::{}Transition => make_transition_style_property(&self.get_{}_transition()),",
            camelize(&p.name),
            snake(&p.name)
        );
        if arm.len() <= MAX_WIDTH {
            w.line(&arm);
        } else {
            w.line(&format!("            Property::{}Transition => {{", camelize(&p.name)));
            w.line(&format!(
                "                make_transition_style_property(&self.get_{}_transition())",
                snake(&p.name)
            ));
            w.line("            }");
        }
    }
    w.line("        }");
    w.line("    }");
    w.blank();

    for p in properties {
        let tag = type_name(class_name, p);
        let s = snake(&p.name);
        let pv = property_value_type(p);
        w.line("    #[must_use]");
        w.line(&format!("    pub fn get_{s}(&self) -> {pv} {{"));
        w.line(&format!("        self.impl_.properties.get::<{tag}>().value.clone()"));
        w.line("    }");
        w.blank();
        w.line(&format!("    pub fn set_{s}(&mut self, property: {pv}) {{"));
        w.line("        let mut impl_ = self.mutable_impl();");
        w.line(&format!("        impl_.properties.get_mut::<{tag}>().value = property;"));
        w.line("        self.impl_ = Arc::new(impl_);");
        w.line("    }");
        w.blank();
        w.line(&format!("    pub fn set_{s}_transition(&mut self, options: &TransitionOptions) {{"));
        w.line("        let mut impl_ = self.mutable_impl();");
        w.line(&format!("        impl_.properties.get_mut::<{tag}>().options = *options;"));
        w.line("        self.impl_ = Arc::new(impl_);");
        w.line("    }");
        w.blank();
        w.line("    #[must_use]");
        w.line(&format!("    pub fn get_{s}_transition(&self) -> TransitionOptions {{"));
        w.line(&format!("        self.impl_.properties.get::<{tag}>().options"));
        w.line("    }");
        w.blank();
    }
    w.finish_block();
    w.line("}");
    w.finish()
}
