//! The tables that `mln_engine`'s Arabic shaping reads (`src/text/arabic_tables.rs`):
//! the presentation forms from the `<isolated>`, `<final>`, `<initial>` and
//! `<medial>` decompositions in `UnicodeData.txt`, checked against the joining
//! types in `ArabicShaping.txt`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::{bmp, code_point, ucd_rows, ucd_version};

const LAM: u32 = 0x0644;
const TATWEEL: u32 = 0x0640;
const SPACE: u32 = 0x0020;
/// The decompositions' tags of the forms, in the order the tables store them.
const FORM_TAGS: [&str; 4] = ["<isolated>", "<final>", "<initial>", "<medial>"];
const ISOLATED: usize = 0;
const MEDIAL: usize = 3;

pub(crate) fn table(arabic_shaping: &str, unicode_data: &str) -> Result<String, String> {
    let version = ucd_version(arabic_shaping, "ArabicShaping")?;
    let mut categories = BTreeMap::new();
    // Each presentation form, its form's index in FORM_TAGS and what it
    // decomposes to.
    let mut presentation_forms = Vec::new();
    for fields in ucd_rows(unicode_data) {
        let [code, _, category, _, _, decomposition, ..] = fields[..] else {
            return Err(format!("{fields:?} isn't a UnicodeData.txt row"));
        };
        let code = code_point(code)?;
        categories.insert(code, category);
        let mut decomposition = decomposition.split_whitespace();
        if let Some(form) = decomposition.next().and_then(|tag| FORM_TAGS.iter().position(|form| *form == tag)) {
            let components = decomposition.map(code_point).collect::<Result<Vec<_>, _>>()?;
            presentation_forms.push((bmp(code)?, form, components));
        }
    }
    let joining_types = JoiningTypes::new(arabic_shaping, categories)?;

    let mut letters: BTreeMap<u16, [u16; 4]> = BTreeMap::new();
    let mut lam_alef: BTreeMap<u16, [u16; 2]> = BTreeMap::new();
    let mut marks: BTreeMap<u16, [u16; 2]> = BTreeMap::new();
    for (code, form, components) in presentation_forms {
        match components[..] {
            [letter] => {
                let forms = letters.entry(bmp(letter)?).or_default();
                if forms[form] != 0 {
                    return Err(format!("two {} forms of U+{letter:04X}", FORM_TAGS[form]));
                }
                forms[form] = code;
            }
            // Lam with a right-joining letter, which ends the join: the
            // lam-alef ligatures, isolated or final.
            [LAM, alef] if joining_types.get(alef) == "R" => {
                let forms = lam_alef.entry(bmp(alef)?).or_default();
                *forms
                    .get_mut(form)
                    .ok_or_else(|| format!("U+{code:04X} is a lam-alef ligature's {} form", FORM_TAGS[form]))? = code;
            }
            // A mark on its own (on a space) or on a tatweel.
            [base, mark]
                if joining_types.get(mark) == "T" && matches!((form, base), (ISOLATED, SPACE) | (MEDIAL, TATWEEL)) =>
            {
                marks.entry(bmp(mark)?).or_default()[usize::from(form == MEDIAL)] = code;
            }
            _ => {}
        }
    }

    for (&letter, forms) in &letters {
        // A letter has the forms of its joining type, at most: dual-joining
        // letters all four, right-joining ones isolated and final, and
        // non-joining ones isolated.
        let joining_type = joining_types.get(letter.into());
        let possible = match joining_type {
            "D" => 4,
            "R" => 2,
            "U" => 1,
            _ => return Err(format!("U+{letter:04X} has forms but joining type {joining_type}")),
        };
        if forms[possible..].iter().any(|&form| form != 0) {
            return Err(format!("U+{letter:04X} ({joining_type}) has forms {forms:04X?}"));
        }
    }
    if lam_alef.is_empty() || lam_alef.values().any(|forms| forms.contains(&0)) {
        return Err(format!("lam-alef ligatures without both forms: {lam_alef:04X?}"));
    }
    if marks.is_empty() || marks.values().any(|forms| forms[0] == 0) {
        return Err(format!("marks without an isolated form: {marks:04X?}"));
    }

    let mut out = format!(
        "// Generated by tools/unicode-tables (`mise run generate:unicode-tables`) from the\n\
         // Unicode Character Database's ArabicShaping-{version}.txt and UnicodeData.txt. Do not edit.\n"
    );
    write_table(
        &mut out,
        &[
            "Each letter with presentation forms, and its isolated, final, initial and",
            "medial forms (0 where it has none), sorted by letter.",
        ],
        "LETTER_FORMS",
        &letters,
    );
    write_table(
        &mut out,
        &[
            "Each letter that a lam before it ligates with, and the ligature's isolated",
            "and final forms, sorted by letter.",
        ],
        "LAM_ALEF_FORMS",
        &lam_alef,
    );
    write_table(
        &mut out,
        &[
            "Each mark with presentation forms, and its forms on its own and on a",
            "tatweel (0 where it has none), sorted by mark.",
        ],
        "MARK_FORMS",
        &marks,
    );
    Ok(out)
}

fn write_table<const N: usize>(out: &mut String, doc: &[&str], name: &str, forms: &BTreeMap<u16, [u16; N]>) {
    out.push('\n');
    for line in doc {
        let _ = writeln!(out, "/// {line}");
    }
    let _ = writeln!(out, "pub(crate) static {name}: [(u16, [u16; {N}]); {}] = [", forms.len());
    for (c, forms) in forms {
        let forms: Vec<String> = forms.iter().map(|form| format!("0x{form:04x}")).collect();
        let _ = writeln!(out, "    (0x{c:04x}, [{}]),", forms.join(", "));
    }
    out.push_str("];\n");
}

/// The joining types of `ArabicShaping.txt`, and the general categories that
/// give the ones it doesn't list.
struct JoiningTypes<'a> {
    listed: BTreeMap<u32, &'a str>,
    /// Each `UnicodeData.txt` row's general category. This leaves out the
    /// characters inside the ranges that `<..., First>` and `<..., Last>` rows
    /// bound, which are all letters, surrogates or private use: `Non_Joining`,
    /// as an absent category gives.
    categories: BTreeMap<u32, &'a str>,
}

impl<'a> JoiningTypes<'a> {
    fn new(arabic_shaping: &'a str, categories: BTreeMap<u32, &'a str>) -> Result<Self, String> {
        let listed = ucd_rows(arabic_shaping)
            .map(|fields| match fields[..] {
                [code, _, joining_type, ..] => Ok((code_point(code)?, joining_type)),
                _ => Err(format!("{fields:?} isn't an ArabicShaping.txt row")),
            })
            .collect::<Result<_, String>>()?;
        Ok(Self { listed, categories })
    }

    fn get(&self, c: u32) -> &'a str {
        if let Some(&joining_type) = self.listed.get(&c) {
            return joining_type;
        }
        // ArabicShaping.txt: characters it doesn't list are Transparent if
        // their general category is Mn, Me or Cf, and Non_Joining otherwise.
        if matches!(self.categories.get(&c), Some(&("Mn" | "Me" | "Cf"))) { "T" } else { "U" }
    }
}
