//! The `Bidi_Mirroring_Glyph` table that `mln_engine`'s BiDi reads
//! (`src/text/bidi_mirroring.rs`), from `BidiMirroring.txt`.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::{bmp, code_point, ucd_rows, ucd_version};

/// The pairs on each line of the table.
const PER_LINE: usize = 6;

pub(crate) fn table(bidi_mirroring: &str) -> Result<String, String> {
    let version = ucd_version(bidi_mirroring, "BidiMirroring")?;
    let mut mirrors = BTreeMap::new();
    for fields in ucd_rows(bidi_mirroring) {
        let [source, mirror] = fields[..] else {
            return Err(format!("{fields:?} isn't a character and its mirror"));
        };
        let source = bmp(code_point(source)?)?;
        if mirrors.insert(source, bmp(code_point(mirror)?)?).is_some() {
            return Err(format!("U+{source:04X} is mapped twice"));
        }
    }
    if mirrors.is_empty() {
        return Err("no mappings".into());
    }

    let mut out = format!(
        "// Generated by tools/unicode-tables (`mise run generate:unicode-tables`) from the\n\
         // Unicode Character Database's BidiMirroring-{version}.txt. Do not edit.\n\
         \n\
         /// Each character with a `Bidi_Mirroring_Glyph`, and that glyph, sorted by\n\
         /// character.\n\
         pub(crate) static BIDI_MIRRORING_GLYPH: [(u16, u16); {}] = [\n",
        mirrors.len()
    );
    let pairs: Vec<String> =
        mirrors.iter().map(|(source, mirror)| format!("(0x{source:04x}, 0x{mirror:04x})")).collect();
    for row in pairs.chunks(PER_LINE) {
        let _ = writeln!(out, "    {},", row.join(", "));
    }
    out.push_str("];\n");
    Ok(out)
}
