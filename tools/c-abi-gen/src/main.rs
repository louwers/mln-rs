//! Generates `crates/mln_c/src/generated` from the C headers in
//! `crates/mln_c/include` (`just generate-c-abi`):
//!
//! - `types.rs`: the headers' types and constants, from bindgen.
//! - `stubs.rs`: for each header function that `crates/mln_c` doesn't define
//!   itself, an exported function with the header's signature that does
//!   nothing and fails: it returns `MLN_STATUS_UNSUPPORTED` and writes a
//!   diagnostic when the function takes one, returns zero, null or `None` when
//!   it returns another value, and leaves every out-parameter as it found it.
//! - `signatures.rs`: a compile-time check that each function `crates/mln_c`
//!   defines itself has the header's signature.
//!
//! A function counts as defined when a `#[unsafe(no_mangle)]` function of its
//! name is in a file under `crates/mln_c/src` outside `generated/`, at the
//! module path that the file's path names.
//!
//! Running it needs libclang, which bindgen loads at run time
//! (`LIBCLANG_PATH` names its directory when the default search misses it).

use std::collections::BTreeMap;
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use proc_macro2::TokenStream;
use quote::{ToTokens, format_ident, quote};
use syn::{FnArg, ForeignItem, Item, ReturnType, Signature, Type};

const HEADER_LINE: &str =
    "// Generated by tools/c-abi-gen from crates/mln_c/include (`just generate-c-abi`). Do not edit.\n";

fn main() -> Result<(), Box<dyn Error>> {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../crates/mln_c").canonicalize()?;
    let include_dir = crate_dir.join("include");
    let src_dir = crate_dir.join("src");
    let out_dir = src_dir.join("generated");

    let headers = headers(&include_dir)?;
    let (types, functions) = bind(&include_dir, &headers)?;
    let defined = defined_functions(&src_dir, &out_dir)?;

    if let Some(name) = defined.keys().find(|name| !functions.iter().any(|f| f.ident == name.as_str())) {
        return Err(format!("crates/mln_c defines {name}, which no header declares").into());
    }

    let aliases: BTreeMap<String, Type> = types
        .iter()
        .filter_map(|item| match item {
            Item::Type(alias) => Some((alias.ident.to_string(), (*alias.ty).clone())),
            _ => None,
        })
        .collect();
    let mut stubs = Vec::new();
    let mut checks = Vec::new();
    for function in &functions {
        match defined.get(&function.ident.to_string()) {
            Some(path) => checks.push(signature_check(function, path)?),
            None => stubs.push(stub(function, &aliases)?),
        }
    }

    let (function_count, stub_count) = (functions.len(), stubs.len());
    fs::create_dir_all(&out_dir)?;
    write(&out_dir.join("types.rs"), "", types)?;
    // Without a stub, the import would be unused.
    let stubs_prelude = if stubs.is_empty() { "" } else { "use super::types::*;\n\n" };
    write(&out_dir.join("stubs.rs"), stubs_prelude, stubs)?;
    write(&out_dir.join("signatures.rs"), "use super::types::*;\n\n", checks)?;
    println!(
        "{function_count} functions from {} headers: {} defined, {stub_count} stubs",
        headers.len(),
        function_count - stub_count,
    );
    Ok(())
}

/// Every header under `include/maplibre_native_c`, and the umbrella header,
/// relative to `include`, sorted so the output doesn't depend on the file
/// system's order.
fn headers(include_dir: &Path) -> Result<Vec<String>, Box<dyn Error>> {
    let mut headers = vec!["maplibre_native_c.h".to_owned()];
    let mut stack = vec![include_dir.join("maplibre_native_c")];
    let mut found = Vec::new();
    while let Some(dir) = stack.pop() {
        for entry in fs::read_dir(&dir)? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|extension| extension == "h") {
                let relative = path.strip_prefix(include_dir)?;
                found.push(relative.to_str().ok_or("a header path is not UTF-8")?.replace('\\', "/"));
            }
        }
    }
    found.sort();
    headers.extend(found);
    Ok(headers)
}

/// Runs bindgen over the headers and splits its output into the type and
/// constant items and the function declarations.
fn bind(include_dir: &Path, headers: &[String]) -> Result<(Vec<Item>, Vec<Signature>), Box<dyn Error>> {
    let mut wrapper = String::new();
    for header in headers {
        writeln!(wrapper, "#include <{header}>")?;
    }
    let include = include_dir.to_str().ok_or("the include path is not UTF-8")?;
    let bindings = bindgen::Builder::default()
        .header_contents("mln_c_abi_gen.h", &wrapper)
        // The headers are C23 (enums with fixed underlying types). MLN_BINDGEN
        // leaves out their inline helpers for C callers, as for every binding.
        .clang_args(["-std=c23", "-DMLN_BINDGEN", &format!("-I{include}")])
        .allowlist_file(format!("{}/.*", regex_escape(include)))
        // A C enum value can be any value of its underlying type, which a Rust
        // enum can't hold: constants of that type instead.
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        // Layout assertions would hold only for the target generated on.
        .layout_tests(false)
        .use_core()
        .generate_cstr(true)
        .merge_extern_blocks(true)
        .rust_target(bindgen::RustTarget::stable(85, 0).map_err(|error| error.to_string())?)
        .rust_edition(bindgen::RustEdition::Edition2024)
        .formatter(bindgen::Formatter::None)
        .generate()?;
    let file = syn::parse_file(&bindings.to_string())?;

    let mut types = Vec::new();
    let mut functions = Vec::new();
    for item in file.items {
        match item {
            Item::ForeignMod(foreign) => {
                for foreign_item in foreign.items {
                    match foreign_item {
                        ForeignItem::Fn(function) => functions.push(function.sig),
                        other => {
                            return Err(format!("unexpected extern item: {}", other.to_token_stream()).into());
                        }
                    }
                }
            }
            other => types.push(other),
        }
    }
    functions.sort_by_key(|function| function.ident.to_string());
    Ok((types, functions))
}

fn regex_escape(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for c in text.chars() {
        if "\\.+*?()|[]{}^$".contains(c) {
            escaped.push('\\');
        }
        escaped.push(c);
    }
    escaped
}

/// The `#[unsafe(no_mangle)]` functions under `src_dir`, outside `skip_dir`,
/// by name, with the module path that holds each.
fn defined_functions(src_dir: &Path, skip_dir: &Path) -> Result<BTreeMap<String, String>, Box<dyn Error>> {
    let mut defined = BTreeMap::new();
    let mut stack = vec![src_dir.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in fs::read_dir(&dir)? {
            let path = entry?.path();
            if path == skip_dir {
                continue;
            }
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|extension| extension == "rs") {
                let file = syn::parse_file(&fs::read_to_string(&path)?)?;
                collect_defined(&file.items, &module_path(src_dir, &path)?, &mut defined)?;
            }
        }
    }
    Ok(defined)
}

/// `crate::a::b` for `src/a/b.rs` or `src/a/b/mod.rs`, `crate` for `src/lib.rs`.
fn module_path(src_dir: &Path, file: &Path) -> Result<String, Box<dyn Error>> {
    let mut path = String::from("crate");
    let relative: PathBuf = file.strip_prefix(src_dir)?.with_extension("");
    for component in &relative {
        let component = component.to_str().ok_or("a source path is not UTF-8")?;
        if component != "lib" && component != "mod" {
            path.push_str("::");
            path.push_str(component);
        }
    }
    Ok(path)
}

fn collect_defined(items: &[Item], module: &str, defined: &mut BTreeMap<String, String>) -> Result<(), Box<dyn Error>> {
    for item in items {
        match item {
            Item::Fn(function) if function.attrs.iter().any(is_no_mangle) => {
                let name = function.sig.ident.to_string();
                if let Some(other) = defined.insert(name.clone(), module.to_owned()) {
                    return Err(format!("{name} is defined in both {other} and {module}").into());
                }
            }
            Item::Mod(inner) => {
                if let Some((_, items)) = &inner.content {
                    collect_defined(items, &format!("{module}::{}", inner.ident), defined)?;
                }
            }
            _ => {}
        }
    }
    Ok(())
}

fn is_no_mangle(attr: &syn::Attribute) -> bool {
    attr.path().is_ident("no_mangle")
        || (attr.path().is_ident("unsafe") && attr.meta.to_token_stream().to_string().contains("no_mangle"))
}

/// `ty` with its typedefs resolved.
fn resolve<'a>(mut ty: &'a Type, aliases: &'a BTreeMap<String, Type>) -> &'a Type {
    while let Type::Path(path) = ty {
        match path.path.get_ident().and_then(|ident| aliases.get(&ident.to_string())) {
            Some(aliased) => ty = aliased,
            None => break,
        }
    }
    ty
}

fn stub(function: &Signature, aliases: &BTreeMap<String, Type>) -> Result<Item, Box<dyn Error>> {
    let ident = &function.ident;
    let inputs = &function.inputs;
    let output = &function.output;
    let name = ident.to_string();
    let body = match output {
        ReturnType::Default => quote! {},
        ReturnType::Type(_, ty) if ty.to_token_stream().to_string().ends_with("_status") => {
            if !matches!(ty.as_ref(), Type::Path(path) if path.path.is_ident("mln_status")) {
                return Err(format!(
                    "{name} returns {}, whose failure value the generator doesn't know: define it in crates/mln_c",
                    ty.to_token_stream()
                )
                .into());
            }
            if takes_diagnostic(function) {
                quote! { unsafe { crate::diagnostic::unsupported(out_diagnostic, #name) } }
            } else {
                quote! { MLN_STATUS_UNSUPPORTED }
            }
        }
        ReturnType::Type(_, ty) => match resolve(ty, aliases) {
            Type::Ptr(pointer) if pointer.mutability.is_some() => quote! { core::ptr::null_mut() },
            Type::Ptr(_) => quote! { core::ptr::null() },
            Type::Path(path) if path.path.segments.last().is_some_and(|segment| segment.ident == "Option") => {
                quote! { None }
            }
            // An integer, or a typedef of one; anything else fails to compile.
            Type::Path(_) => quote! { 0 },
            other => return Err(format!("{name} returns {}, which has no stub", other.to_token_stream()).into()),
        },
    };
    Ok(syn::parse2(quote! {
        #[unsafe(no_mangle)]
        pub unsafe extern "C" fn #ident(#inputs) #output {
            #body
        }
    })?)
}

fn takes_diagnostic(function: &Signature) -> bool {
    function.inputs.iter().any(|input| match input {
        FnArg::Typed(typed) => {
            typed.pat.to_token_stream().to_string() == "out_diagnostic"
                && typed.ty.to_token_stream().to_string() == "* mut mln_diagnostic"
        }
        FnArg::Receiver(_) => false,
    })
}

fn signature_check(function: &Signature, module: &str) -> Result<Item, Box<dyn Error>> {
    let ident = &function.ident;
    let output = &function.output;
    let types = function.inputs.iter().map(|input| match input {
        FnArg::Typed(typed) => typed.ty.to_token_stream(),
        FnArg::Receiver(receiver) => receiver.to_token_stream(),
    });
    let mut path = TokenStream::new();
    for (index, segment) in module.split("::").enumerate() {
        let segment = format_ident!("{segment}");
        if index > 0 {
            path.extend(quote! { :: });
        }
        path.extend(quote! { #segment });
    }
    Ok(syn::parse2(quote! {
        const _: unsafe extern "C" fn(#(#types),*) #output = #path::#ident;
    })?)
}

fn write(path: &Path, prelude: &str, items: Vec<Item>) -> Result<(), Box<dyn Error>> {
    let file = syn::File { shebang: None, attrs: Vec::new(), items };
    fs::write(path, format!("{HEADER_LINE}\n{prelude}{}", prettyplease::unparse(&file)))?;
    Ok(())
}
